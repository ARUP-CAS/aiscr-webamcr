"""Render, check, and validate testing-scenario corpus index.

A testing-scenario corpus lives in the repository whose deployed service it describes, under
``.agents/reports/testing_scenarios/``. Its source of truth is ``index.toml``; the view ``INDEX.md`` is generated from
it and never hand-edited, and a stale view is an error. A run resolves the scenarios relevant to its issue from the
index's declared coverage — never from filenames — and a scenario file the index does not carry is reported as an
omission.

``schema_version = 1``; one ``[[scenario]]`` table per scenario:

```toml
schema_version = 1

[[scenario]]
key = "export"                 # stable file identity; the file is <key>.md
kind = "feature"               # "feature" by default, "entity" by exception
title = "Export"               # human-readable scenario title
features = ["export"]          # features covered (non-empty for kind=feature)
entities = ["record"]          # entities covered (non-empty for kind=entity)
surfaces = ["export page"]     # surfaces exercised within the scenario
issues = ["owner/repo#148"]    # issues that drove it
last_verified = "2026-08-28"   # date of the most recent verification
```

The engine reads structured input with the Python standard library only (``tomllib``). ``render`` regenerates the view;
``check`` reports schema violations, a stale or missing view, an index entry whose scenario file is absent, and a
scenario file present with no index entry; ``merge`` upserts one scenario entry into a base index and writes the merged
result: every base ``[[scenario]]`` entry it did not upsert survives, an absent or empty base is the legitimate
first-run input, and the merged index is validated against the schema before it is written. ``validate`` reports
structural corruption in the scenario documents the index declares — carriage-return bytes, blank-line runs longer than
one, blank lines inside a table's header block, and trailing whitespace. Exit codes: 0 clean, 1 findings, 2 the corpus
could not be evaluated.

Contract: review/live-acceptance-verification
Class: tool
Exit codes: 0 clean; 1 findings; 2 the corpus could not be evaluated
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

try:  # ``tomllib`` is standard library from Python 3.11 onward.
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - exercised on unsupported interpreters
    tomllib = None  # type: ignore[assignment] # pylint: disable=invalid-name

from lib.log_utils import log_error, log_info  # noqa: E402

MIN_PYTHON = (3, 11)

#: Index schema versions this engine understands.
SCHEMA_VERSIONS = frozenset({"1"})

#: Allowed scenario ownership kinds: a feature by default, an entity by exception.
KINDS = frozenset({"feature", "entity"})

INDEX_NAME = "index.toml"
VIEW_NAME = "INDEX.md"
README_NAME = "README.md"

#: A scenario key doubles as a filename stem, so it stays lowercase and hyphenated.
KEY_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]*$")

DATE_PATTERN = re.compile(r"^\d{4}-\d{2}-\d{2}$")

GENERATED_HEADER = f"<!-- generated by testing_scenario_corpus.py from {INDEX_NAME} -- do not hand-edit -->"

CORPUS_DEFAULT = Path(".agents") / "reports" / "testing_scenarios"


class CorpusError(Exception):
    """The corpus index could not be read or is malformed."""


def require_supported_python() -> None:
    """Fail with an explicit version message instead of a ``tomllib`` traceback."""
    if tomllib is None or sys.version_info < MIN_PYTHON:
        current = ".".join(str(part) for part in sys.version_info[:3])
        raise SystemExit(
            f"testing_scenario_corpus.py requires Python {MIN_PYTHON[0]}.{MIN_PYTHON[1]} or newer "
            f"(found {current}); it reads TOML with the standard-library tomllib module."
        )


def load_index(corpus: Path) -> dict[str, Any]:
    """Load ``index.toml``, raising :class:`CorpusError` when it is absent or invalid."""
    require_supported_python()
    path = corpus / INDEX_NAME
    if not path.is_file():
        raise CorpusError(f"missing corpus index: {path}")
    return load_toml_file(path, label=INDEX_NAME)


def load_toml_file(path: Path, label: str | None = None) -> dict[str, Any]:
    """Load one TOML file, raising :class:`CorpusError` on a missing, unreadable, or invalid file.

    Any ``OSError`` from the open maps to :class:`CorpusError` too: an unreadable TOML source is the failure outcome,
    not an empty baseline and not an uncaught traceback.
    """
    require_supported_python()
    shown = label or str(path)
    try:
        with path.open("rb") as handle:
            return tomllib.load(handle)
    except FileNotFoundError as exc:
        raise CorpusError(f"missing TOML file: {shown}") from exc
    except OSError as exc:
        raise CorpusError(f"cannot read TOML file: {shown}: {exc}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise CorpusError(f"invalid TOML in {shown}: {exc}") from exc


def _validate_list(value: Any, field: str, key: str, findings: list[str]) -> list[str]:
    """Append a finding unless *value* is a non-empty list of non-empty strings."""
    if not isinstance(value, list) or not value:
        findings.append(f"scenario '{key}': '{field}' must be a non-empty list")
        return findings
    if any(not isinstance(item, str) or not item.strip() for item in value):
        findings.append(f"scenario '{key}': '{field}' entries must be non-empty strings")
    return findings


def _validate_entry(entry: dict[str, Any], seen: set[str], findings: list[str]) -> None:
    """Append schema findings for one ``[[scenario]]`` table."""
    key = entry.get("key")
    if not isinstance(key, str) or not KEY_PATTERN.match(key):
        findings.append(f"scenario table: 'key' must be a lowercase hyphenated string, found {key!r}")
        return
    if key in seen:
        findings.append(f"scenario '{key}': duplicate key")
        return
    seen.add(key)

    kind = entry.get("kind")
    if kind not in KINDS:
        findings.append(f"scenario '{key}': 'kind' must be one of {sorted(KINDS)}, found {kind!r}")
    if not isinstance(entry.get("title"), str) or not entry.get("title", "").strip():
        findings.append(f"scenario '{key}': 'title' must be a non-empty string")
    last_verified = entry.get("last_verified")
    if not isinstance(last_verified, str) or not DATE_PATTERN.match(last_verified):
        findings.append(f"scenario '{key}': 'last_verified' must be an ISO date (YYYY-MM-DD)")

    for field in ("features", "surfaces", "issues"):
        _validate_list(entry.get(field), field, key, findings)
    entities = entry.get("entities", [])
    if not isinstance(entities, list) or any(not isinstance(item, str) or not item.strip() for item in entities):
        findings.append(f"scenario '{key}': 'entities' must be a list of non-empty strings")
    elif kind == "entity" and not entities:
        findings.append(f"scenario '{key}': an entity-keyed scenario must list its entities")
    elif kind == "feature" and not entry.get("features"):
        findings.append(f"scenario '{key}': a feature-keyed scenario must list its features")


def validate_index(data: dict[str, Any]) -> list[str]:
    """Return schema findings for a parsed index; an empty list means the index is valid."""
    findings: list[str] = []
    declared = data.get("schema_version")
    if declared is None:
        findings.append(f"{INDEX_NAME}: missing 'schema_version'")
    elif str(declared) not in SCHEMA_VERSIONS:
        known = ", ".join(sorted(SCHEMA_VERSIONS))
        findings.append(f"{INDEX_NAME}: unrecognized schema_version '{declared}' (known: {known})")

    scenarios = data.get("scenario")
    if not isinstance(scenarios, list) or not scenarios:
        findings.append(f"{INDEX_NAME}: no [[scenario]] tables")
        return findings

    seen: set[str] = set()
    for entry in scenarios:
        if not isinstance(entry, dict):
            findings.append(f"{INDEX_NAME}: a [[scenario]] table is not a mapping")
            continue
        _validate_entry(entry, seen, findings)
    return findings


def render_view(data: dict[str, Any]) -> str:
    """Render the deterministic Markdown view of a validated index."""
    lines = [
        GENERATED_HEADER,
        "",
        "# Testing scenario index",
        "",
        "| Scenario | Kind | Features | Entities | Surfaces | Driving issues | Last verified |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in sorted(data.get("scenario", []), key=lambda item: str(item.get("key", ""))):
        key = str(entry.get("key", ""))
        cells = {
            "scenario": f"[`{key}`]({key}.md)",
            "kind": str(entry.get("kind", "")),
            "features": ", ".join(entry.get("features", [])),
            "entities": ", ".join(entry.get("entities", [])),
            "surfaces": ", ".join(entry.get("surfaces", [])),
            "issues": ", ".join(entry.get("issues", [])),
            "verified": str(entry.get("last_verified", "")),
        }
        row = [value.replace("|", "\\|") for value in cells.values()]
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return "\n".join(lines)


def scenario_files(corpus: Path) -> list[str]:
    """Return the scenario documents in the corpus, excluding the README and the view."""
    return sorted(path.name for path in corpus.glob("*.md") if path.name not in (README_NAME, VIEW_NAME))


#: TOML bare-key shape. A base index may legally carry quoted keys containing any
#: character; the merge refuses them rather than emitting a corrupted structure.
BARE_KEY_PATTERN = re.compile(r"^[A-Za-z0-9_-]+$")


def _toml_string(value: str) -> str:
    r"""Serialize a string as a TOML basic-string literal.

    JSON's string literal is TOML's basic-string literal, including the full control-character ``\\uXXXX`` coverage a
    hand-rolled escape table misses; the established writers in this repository serialize identically.
    """
    return json.dumps(value, ensure_ascii=False)


def _toml_value(value: Any) -> str:
    """Serialize one TOML value; the merge refuses a type it cannot write safely."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, list):
        if not all(isinstance(item, str) for item in value):
            raise CorpusError("merge can only serialize lists of strings")
        return "[" + ", ".join(_toml_string(item) for item in value) + "]"
    raise CorpusError(f"merge cannot serialize a value of type {type(value).__name__}")


def dump_index(data: dict[str, Any]) -> str:
    """Serialize a parsed index back to TOML text, preserving entry and key order."""
    lines: list[str] = []

    def require_bare_key(key: Any) -> str:
        if not isinstance(key, str) or not BARE_KEY_PATTERN.match(key):
            raise CorpusError(f"merge refuses a non-bare TOML key: {key!r}")
        return key

    for key, value in data.items():
        if key == "scenario":
            continue
        lines.append(f"{require_bare_key(key)} = {_toml_value(value)}")
    lines.append("")
    for entry in data.get("scenario", []):
        lines.append("[[scenario]]")
        for key, value in entry.items():
            lines.append(f"{require_bare_key(key)} = {_toml_value(value)}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def merge_index(base_data: dict[str, Any], entry: dict[str, Any]) -> dict[str, Any]:
    """Upsert *entry* into *base_data* by scenario key, preserving base order.

    A replaced key keeps its base position; a new key is appended. Every base entry the upsert does not touch survives
    untouched.
    """
    merged = {key: value for key, value in base_data.items() if key != "scenario"}
    merged.setdefault("schema_version", 1)
    scenarios = list(base_data.get("scenario") or [])
    for position, existing in enumerate(scenarios):
        if isinstance(existing, dict) and existing.get("key") == entry.get("key"):
            scenarios[position] = entry
            break
    else:
        scenarios.append(entry)
    merged["scenario"] = scenarios
    return merged


def cmd_merge(corpus: Path, base: Path | None, entry_path: Path) -> int:
    """Upsert one scenario entry into a base index and write the merged result.

    An absent or empty base is the legitimate first-run input and yields a single-entry index; an invalid base is an
    error, never an empty baseline.
    """
    fragment = load_toml_file(entry_path)
    fragment_scenarios = fragment.get("scenario")
    if (
        not isinstance(fragment_scenarios, list)
        or len(fragment_scenarios) != 1
        or not isinstance(fragment_scenarios[0], dict)
    ):
        raise CorpusError(f"merge entry fragment must carry exactly one [[scenario]] table: {entry_path}")
    entry = fragment_scenarios[0]

    if base is None or not base.exists():
        base_data: dict[str, Any] = {}
        where = f"at {base}" if base is not None else "given"
        log_info(f"no base index {where}; treating as the first run")
    elif not base.is_file():
        raise CorpusError(f"merge base exists but is not a file: {base}")
    else:
        base_data = load_toml_file(base)

    merged = merge_index(base_data, entry)
    findings = validate_index(merged)
    if findings:
        for finding in findings:
            log_error(finding)
        return 2
    out_path = corpus / INDEX_NAME
    out_path.write_bytes(dump_index(merged).encode("utf-8"))
    count = len(merged["scenario"])
    noun = "entry" if count == 1 else "entries"
    log_info(f"merged {count} scenario {noun}; wrote {out_path}")
    return 0


def _read_view(corpus: Path) -> str | None:
    """Return the view's text with normalized newlines, or None when absent."""
    path = corpus / VIEW_NAME
    if not path.is_file():
        return None
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def cmd_render(corpus: Path) -> int:
    """Regenerate the corpus view from the index."""
    data = load_index(corpus)
    findings = validate_index(data)
    if findings:
        for finding in findings:
            log_error(finding)
        return 2
    view_path = corpus / VIEW_NAME
    view_path.write_bytes(render_view(data).encode("utf-8"))
    log_info(f"[INFO] wrote {view_path}")
    return 0


def _is_table_row(line: str) -> bool:
    """Return True when *line* starts a Markdown table row."""
    return line.lstrip().startswith("|")


def _is_table_separator(line: str) -> bool:
    """Return True when *line* is a Markdown table separator row (``| --- |``)."""
    stripped = line.strip()
    return stripped.startswith("|") and "-" in stripped and set(stripped) <= set("|-: \t")


def validate_markdown_text(text: str, label: str) -> list[str]:
    """Return structural-corruption findings for one scenario document.

    Every rule describes a shape no generated or hand-maintained corpus document legitimately holds, so a finding is
    corruption, not style: a carriage return (the corpus is LF), a blank-line run longer than one, a blank line inside a
    table's header block (header, separator, or first data row), or trailing whitespace on a line. Two adjacent tables
    separated by a single blank line are not findings: their gap sits between a data row and the next table's header
    row, which no rule matches.
    """
    findings: list[str] = []
    if "\r" in text:
        findings.append(f"{label}: carriage-return bytes (CRLF or CR line endings; the corpus is LF)")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    run_length = 0
    for index, line in enumerate(lines, start=1):
        if line.strip() == "":
            run_length += 1
            continue
        if run_length > 1:
            findings.append(
                f"{label}: blank-line run of {run_length} ending at line {index - 1} "
                "(a single blank line separates blocks)"
            )
        run_length = 0
        if line != line.rstrip(" \t"):
            findings.append(f"{label}: trailing whitespace on line {index}")
    for index in range(len(lines) - 2):
        if lines[index + 1].strip() != "":
            continue
        before, after = lines[index], lines[index + 2]
        if _is_table_row(before) and _is_table_separator(after):
            findings.append(f"{label}: blank line inside the table header block (line {index + 2})")
        elif _is_table_separator(before) and _is_table_row(after):
            findings.append(f"{label}: blank line inside the table header block (line {index + 2})")
    return findings


def cmd_validate(corpus: Path) -> int:
    """Report structural corruption in the scenario documents the index declares."""
    data = load_index(corpus)
    findings = validate_index(data)
    scenarios = data.get("scenario")
    if not isinstance(scenarios, list):
        scenarios = []
    keys = sorted(
        str(entry.get("key")) for entry in scenarios if isinstance(entry, dict) and isinstance(entry.get("key"), str)
    )
    for key in keys:
        path = corpus / f"{key}.md"
        if not path.is_file():
            continue  # a missing scenario file is validate_index's finding, not this pass's
        try:
            # decode bytes rather than read_text: text mode translates CRLF to LF
            # and would mask the carriage returns this pass exists to catch
            text = path.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            findings.append(f"scenario '{key}' cannot be read: {exc}")
            continue
        findings.extend(validate_markdown_text(text, f"{key}.md"))
    if findings:
        for finding in findings:
            log_error(finding)
        return 1
    log_info(f"[INFO] {corpus}: scenario documents are structurally clean")
    return 0


def cmd_check(corpus: Path) -> int:
    """Report corpus drift: schema violations, stale view, and index/file mismatches."""
    findings: list[str] = []
    data = load_index(corpus)

    findings.extend(validate_index(data))
    scenarios = data.get("scenario")
    if not isinstance(scenarios, list):
        scenarios = []
    indexed = {
        str(entry.get("key")) for entry in scenarios if isinstance(entry, dict) and isinstance(entry.get("key"), str)
    }
    for name in scenario_files(corpus):
        if name[: -len(".md")] not in indexed:
            findings.append(f"scenario file '{name}' is present but has no index entry")
    for key in sorted(indexed):
        if not (corpus / f"{key}.md").is_file():
            findings.append(f"scenario '{key}' is indexed but its file '{key}.md' is missing")

    if not findings:
        view = _read_view(corpus)
        if view is None:
            findings.append(f"missing corpus view: {corpus / VIEW_NAME}")
        elif view != render_view(data):
            findings.append(f"stale corpus view: {VIEW_NAME} does not match generation from {INDEX_NAME}")

    if findings:
        for finding in findings:
            log_error(finding)
        return 1
    log_info(f"[INFO] {corpus}: index, view, and scenario files agree")
    return 0


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest="subcommand", required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--corpus", type=Path, default=CORPUS_DEFAULT, help="corpus directory")
    subparsers.add_parser("render", parents=[common], help="regenerate the view from the index")
    subparsers.add_parser("check", parents=[common], help="report a stale view and index/file mismatches")
    subparsers.add_parser("validate", parents=[common], help="report structural corruption in the scenario documents")
    merge_parser = subparsers.add_parser(
        "merge", parents=[common], help="upsert one scenario entry into a base index and write the merged result"
    )
    merge_parser.add_argument(
        "--base",
        type=Path,
        default=None,
        help="base index to merge onto; an absent or empty base is the first-run input",
    )
    merge_parser.add_argument(
        "--entry",
        type=Path,
        required=True,
        help="TOML fragment carrying exactly one [[scenario]] table to upsert",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Parse CLI arguments and dispatch to the selected subcommand."""
    args = build_parser().parse_args(argv)
    corpus = args.corpus
    if not corpus.is_dir():
        log_error(f"corpus directory not found: {corpus}")
        return 2
    try:
        if args.subcommand == "render":
            return cmd_render(corpus)
        if args.subcommand == "validate":
            return cmd_validate(corpus)
        if args.subcommand == "merge":
            return cmd_merge(corpus, args.base, args.entry)
        return cmd_check(corpus)
    except CorpusError as exc:
        log_error(str(exc))
        return 2


if __name__ == "__main__":  # pragma: no cover -- exercised through main()
    sys.exit(main())
